export const getAppName = () => {
  const PageURL = window.location.href?.toLowerCase();

  if (PageURL.includes("employee-directory-365") || PageURL.includes("directory")) {
    return "Employee Directory 365";
  } else if (PageURL.includes("helpdesk-365") || PageURL.includes("helpdesk") || PageURL.includes("helpdesk-software")) {
    return "Helpdesk 365";
  } else if (PageURL.includes("asset-management-365") || PageURL.includes("asset")) {
    return "Asset 365";
  } else if (PageURL.includes("time-off-manager-365") || PageURL.includes("leave") || PageURL.includes("leave-management")) {
    return "Time Off Manager 365";
  } else if (PageURL.includes("employee-onboarding-365") || PageURL.includes("onboarding")) {
    return "Employee Onboarding 365";
  } else if (PageURL.includes("performance-management-365") || PageURL.includes("performance")) {
    return "Performance Management 365";
  } else if (PageURL.includes("sharepoint-contract-management-software") || PageURL.includes("contract-management-365") || PageURL.includes("contract")) {
    return "CLM 365 - Contract Management";
  } else if (PageURL.includes("task-management-365") || PageURL.includes("task")) {
    return "Task 365";
  } else if (PageURL.includes("revenue-365")) {
    return "Revenue 365";
  } else if (PageURL.includes("civic-365")) {
    return "Civic 365";
  } else if (PageURL.includes("hr365-best-hr-management-software-hr") || PageURL.includes("human")) {
    return "HRMS";
  } else if (PageURL.includes("microsoft-recruitment-software") || PageURL.includes("recruitment-365")) {
    return "Recruitment Software 365";
  } else if (PageURL.includes("lms-365") || PageURL.includes("learning-management-365")) {
    return "LMS 365";
  } else if (PageURL.includes("expense-tracker-365") || PageURL.includes("expense-365") || PageURL.includes("expense") || PageURL.includes("expense-tracker")) {
    return "Expense 365";
  } else if (PageURL.includes("sharepoint-timesheet") || PageURL.includes("timesheet-365")) {
    return "Timesheet 365";
  } else {
    return SiteName === "HR365" ? "lp.hr365.us" : "lp.apps365.com";
  }
};